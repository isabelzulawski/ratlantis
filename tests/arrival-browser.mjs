import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const b=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
 const p=await b.newPage({viewport:{width:1200,height:675}}), errors=[];
 p.on('pageerror', e=>errors.push(e.message));
 await p.addInitScript(()=>{if(!localStorage.getItem('ratlantis-opening-v1'))localStorage.setItem('ratlantis-opening-v1',JSON.stringify({version:1,name:'Pip',fur:'Gray',scene:'queens',inventory:['ticket','newspaper'],flags:{acting:true,singing:true,dancing:true,wardrobe:true},journal:[],sound:false}));});
 await p.goto(process.env.RATLANTIS_TEST_URL || 'http://127.0.0.1:5182/');
 await p.locator('#continue').click();
 await p.waitForTimeout(250);
 await p.evaluate(()=>{ratlantis.player.setPosition(900,485);ratlantis.cameras.main.setScroll(300,0);});
 await p.waitForTimeout(350);
 await p.screenshot({path:'tests/quiet-queens.png'});
 const directorX=await p.evaluate(()=>ratlantis.director.x-ratlantis.cameras.main.scrollX);
 await p.mouse.click(directorX,510);
 await p.locator('.speech').waitFor();
 assert.match(await p.locator('.speech').innerText(), /CRAWL THROUGH THE PIPES BACK TO MANHATTAN/i);
 await p.getByRole('button',{name:'Continue',exact:true}).click();
 await p.evaluate(()=>ratlantis.enter('auditionPipe'));
 await p.waitForTimeout(300);await p.screenshot({path:'tests/quiet-conduit.png'});
 await p.evaluate(()=>{ratlantis.player.setPosition(1650,485);ratlantis.cameras.main.setScroll(600,0);});
 await p.waitForTimeout(300);
 await p.mouse.click(1140,500);
 await p.waitForFunction(()=>ratlantis.id==='vent');
 await p.waitForTimeout(350);await p.screenshot({path:'tests/quiet-vent.png'});
 await p.locator('#bag').click();
 assert.equal(await p.evaluate(()=>ratlantis.finale.arrival.opening),false);
 await p.getByRole('button',{name:'Close backpack',exact:true}).click();
 await p.evaluate(()=>ratlantis.player.setPosition(740,485));
 await p.waitForTimeout(350);await p.mouse.click(900,480);
 await p.waitForFunction(()=>ratlantis.id==='auditionRoom');
 await p.getByRole('button',{name:'Return to Ratlantis',exact:true}).waitFor();
 assert.ok(await p.evaluate(()=>ratlantis.state.flags.ventOpened && ratlantis.state.flags.auditionRoomReached && ratlantis.state.flags.finished));
 assert.equal(await p.locator('#overlay .panel').count(),0);
 assert.equal(await p.evaluate(()=>ratlantis.locked),false);
 await p.screenshot({path:'tests/quiet-audition-room.png'});
 const inventory=await p.evaluate(()=>ratlantis.state.inventory);
 await p.reload();await p.locator('#continue').click();await p.waitForTimeout(400);
 assert.equal(await p.evaluate(()=>ratlantis.id),'auditionRoom');
 assert.deepEqual(await p.evaluate(()=>ratlantis.state.inventory),inventory);
 assert.ok(await p.evaluate(()=>ratlantis.player.body.center.x < 335));
 await p.evaluate(()=>{ratlantis.player.setPosition(700,900);});
 await p.waitForTimeout(250);
 assert.ok(await p.evaluate(()=>ratlantis.player.body.center.x < 335 && ratlantis.player.y < 600));
 await p.getByRole('button',{name:'Return to Ratlantis',exact:true}).click();
 assert.equal(await p.evaluate(()=>ratlantis.id),'neighborhood');
 assert.equal(await p.locator('.ending-caption').count(),0);
 assert.deepEqual(errors,[]);
 console.log('Director, pipe route, animated grille, visible room ending, safe reload/recovery and inventory preservation pass.');
} finally {await b.close();}
